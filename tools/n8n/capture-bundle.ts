// The capture's markdown writer (packages/adapters/src/markdown/capture-markdown.ts,
// #103, ADR-0049) bundled into one plain script for n8n's Code node: the same
// serializer and settings the app writes a capture's tree with, so n8n writes
// the same bytes. Bundled with rolldown, vite's own bundler, from vite's install:
// no bundler of its own in the repo's dependencies.
import { createRequire } from 'node:module';

const ROOT = new URL('../../', import.meta.url);
const ENTRY = new URL('packages/adapters/src/markdown/capture-markdown.ts', ROOT);

/** The global the bundle defines: `dfaiCaptureMarkdown.writeCaptureMarkdown`. */
export const CAPTURE_MARKDOWN_GLOBAL = 'dfaiCaptureMarkdown';

/** Where the generated bundle is kept, beside the workflow JSON. */
export const CAPTURE_MARKDOWN_BUNDLE = new URL('capture-markdown.bundle.js', import.meta.url);

/** As much of rolldown's API as is used here; its types are vite's, not the repo's. */
interface Rolldown {
  rolldown(options: Record<string, unknown>): Promise<{
    generate(options: Record<string, unknown>): Promise<{ output: { code: string }[] }>;
    close(): Promise<void>;
  }>;
}

async function rolldownFromVite(): Promise<Rolldown> {
  const desktop = createRequire(new URL('apps/desktop/package.json', ROOT));
  const vite = createRequire(desktop.resolve('vite/package.json'));
  return (await import(vite.resolve('rolldown'))) as Rolldown;
}

/** The writer as one script defining {@link CAPTURE_MARKDOWN_GLOBAL}. */
export async function bundleCaptureMarkdown(): Promise<string> {
  const { rolldown } = await rolldownFromVite();
  const bundle = await rolldown({
    input: ENTRY.pathname,
    platform: 'neutral',
    treeshake: true,
    logLevel: 'warn',
  });
  try {
    const { output } = await bundle.generate({
      format: 'iife',
      name: CAPTURE_MARKDOWN_GLOBAL,
      minify: true,
      banner:
        '// Generated by `pnpm n8n:build` from packages/adapters/src/markdown/capture-markdown.ts: do not edit.',
    });
    return `${output[0]?.code.trimEnd() ?? ''}\n`;
  } finally {
    await bundle.close();
  }
}
